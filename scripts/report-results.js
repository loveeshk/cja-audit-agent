// scripts/report-results.js — runs every retrieval measurement the report needs and saves them in one file.
// Run:  npm run rag:report
// Needs no API key, only the real embedding model (downloaded on first use). Takes about a minute.
//
// It runs, in order:
//   1. npm run rag:eval                     (semantic vs keyword vs hybrid, weight sweep, threshold report)
//   2. the Q1 trace  "Which columns cannot be included in a CJA data feed?"
//   3. the Q2 trace  "Can CJA data feeds be delivered over SFTP?"
// and writes all three outputs, unedited, to examples/retrieval-results.md.

const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'examples', 'retrieval-results.md');
const Q1 = 'Which columns cannot be included in a CJA data feed?';
const Q2 = 'Can CJA data feeds be delivered over SFTP?';

function run(script, args = []) {
  return execFileSync(process.execPath, [path.join(__dirname, script), ...args], {
    cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'], maxBuffer: 32 * 1024 * 1024,
  });
}

console.log('1/3 Retrieval evaluation (the first run downloads the embedding model) ...');
const evalOut = run('eval-retrieval.js');
if (/MOCK EMBEDDER/.test(evalOut)) {
  console.error('The mock embedder is active (RAG_EMBEDDER=mock). Unset it: these results must come from the real model.');
  process.exit(1);
}
console.log('2/3 Trace for Q1 ...');
const q1 = run('trace-table.js', [Q1]);
console.log('3/3 Trace for Q2 ...');
const q2 = run('trace-table.js', [Q2]);

const md = `# Retrieval results (real embedding model)

Generated by \`npm run rag:report\` on ${new Date().toISOString()} with Node ${process.version}.
Unedited output of the three commands below. These are the numbers quoted in
\`docs/final-capstone-report.md\` (section 7) and \`docs/01-retrieval-design.md\` (section 3).

## 1. \`npm run rag:eval\`

\`\`\`
${evalOut.trim()}
\`\`\`

## 2. \`npm run rag:table -- "${Q1}"\`

${q1.trim()}

## 3. \`npm run rag:table -- "${Q2}"\`

${q2.trim()}
`;

fs.writeFileSync(out, md);
console.log(`\nSaved ${path.relative(root, out)}. Send this file back to fill the report, and commit it as an evaluation artifact.`);
